// Generates:
//   custom_components/kirion_atelier/themes/kirion-atelier.yaml  (Home Assistant themes)
//   demo/themes.generated.js                          (same tokens for the preview page)
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { VARIANTS, dark, light } from "./tokens.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const quote = (v) => `"${String(v).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

const themes = {};
for (const [name, accent] of Object.entries(VARIANTS)) {
  themes[name] = { light: light(accent.light), dark: dark(accent.dark) };
}

let yaml = `# KIRION Atelier — minimalist glass themes for Home Assistant.
# GENERATED by tools/build-themes.mjs — edit tools/tokens.mjs instead.
# Pair with KIRION Atelier Glass for real backdrop blur on cards.
`;
for (const [name, modes] of Object.entries(themes)) {
  yaml += `\n${name}:\n  modes:\n`;
  for (const [mode, vars] of Object.entries(modes)) {
    yaml += `    ${mode}:\n`;
    for (const [k, v] of Object.entries(vars)) yaml += `      ${k}: ${quote(v)}\n`;
  }
}

const out = (rel, text) => {
  const p = join(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, text);
  console.log("wrote", rel);
};

out("custom_components/kirion_atelier/themes/kirion-atelier.yaml", yaml);
out(
  "demo/themes.generated.js",
  `// GENERATED by tools/build-themes.mjs\nexport const THEMES = ${JSON.stringify(themes, null, 2)};\n`
);
