"""Write the `kirion` icon set (frontend/kirion-atelier-icons.js) from SVG files.

Run from the repo root:  python3 tools/build_icons.py

Each source must be a single-colour SVG made of filled paths (no strokes, no
text). Paths are merged into one and the viewBox is padded to a square, so the
icon sits centred in Home Assistant's square icon slot.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ICONS = {
    # icon name in Home Assistant → source file
    "atelier": ROOT / "ikonaatelier.svg",
}
OUT = ROOT / "custom_components" / "kirion_atelier" / "frontend" / "kirion-atelier-icons.js"


def load(source: Path) -> dict:
    svg = source.read_text(encoding="utf-8")
    x, y, w, h = (float(v) for v in re.search(r'viewBox="([^"]+)"', svg).group(1).replace(",", " ").split())
    paths = re.findall(r'<path\b[^>]*\sd="([^"]+)"', svg)
    if not paths:
        raise SystemExit(f"{source.name}: no <path> elements")
    if re.search(r"<(text|image|use)\b", svg):
        raise SystemExit(f"{source.name}: convert text and images to paths first")
    side = max(w, h)
    box = [x - (side - w) / 2, y - (side - h) / 2, side, side]
    return {"path": " ".join(paths), "viewBox": " ".join(f"{v:g}" for v in box)}


icons = {name: load(src) for name, src in ICONS.items()}
OUT.write_text(
    """/*! KIRION Atelier Icons
 * GENERATED by tools/build_icons.py — edit the source SVGs instead.
 * Registers the "kirion" icon set (e.g. kirion:atelier) the same way HACS
 * registers hacs:hacs, so it can be used in the sidebar and any icon field.
 */
(() => {
  const ICONS = %s;
  window.customIcons = window.customIcons || {};
  window.customIcons.kirion = {
    getIcon: async (name) => ICONS[name],
    getIconList: async () => Object.keys(ICONS).map((name) => ({ name })),
  };
})();
"""
    % json.dumps(icons, indent=2).replace("\n", "\n  "),
    encoding="utf-8",
)
print("wrote", OUT.relative_to(ROOT), "with", ", ".join(f"kirion:{n}" for n in icons))
