"""Write the `kirion` icon set (frontend/kirion-atelier-icons.js) from SVG files.

Run from the repo root:  python3 tools/build_icons.py

Sources:
  * ikonaatelier.svg             → kirion:atelier (the Atelier Panel icon)
  * assets/icons/phosphor/*.svg  → kirion:<file name>, Phosphor Icons "light"
                                   weight, MIT licence (assets/icons/phosphor/LICENSE)

Each source must be a single-colour SVG made of filled paths (no strokes, no
text). Paths are merged into one and the viewBox is padded to a square, so the
icon sits centred in Home Assistant's square icon slot.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PHOSPHOR = ROOT / "assets" / "icons" / "phosphor"
OUT = ROOT / "custom_components" / "kirion_atelier" / "frontend" / "kirion-atelier-icons.js"
# HACS installs only custom_components/, so the licence text ships next to the icons.
LICENSE_OUT = OUT.with_name("PHOSPHOR-LICENSE.txt")

SOURCES = {"atelier": ROOT / "ikonaatelier.svg"}
SOURCES.update({svg.stem: svg for svg in sorted(PHOSPHOR.glob("*.svg"))})


def load(source: Path) -> dict:
    svg = source.read_text(encoding="utf-8")
    x, y, w, h = (float(v) for v in re.search(r'viewBox="([^"]+)"', svg).group(1).replace(",", " ").split())
    paths = re.findall(r'<path\b[^>]*\sd="([^"]+)"', svg)
    if not paths:
        raise SystemExit(f"{source.name}: no <path> elements")
    if re.search(r"<(text|image|use)\b|stroke=", svg):
        raise SystemExit(f"{source.name}: convert strokes, text and images to filled paths first")
    side = max(w, h)
    box = [x - (side - w) / 2, y - (side - h) / 2, side, side]
    return {"path": " ".join(paths), "viewBox": " ".join(f"{v:g}" for v in box)}


icons = {name: load(src) for name, src in SOURCES.items()}
OUT.write_text(
    """/*! KIRION Atelier Icons
 * SPDX-License-Identifier: GPL-3.0-or-later
 * Copyright (c) 2026 KIRION. See NOTICE for the attribution requirements.
 * GENERATED by tools/build_icons.py — edit the source SVGs instead.
 * Registers the "kirion" icon set (kirion:atelier, kirion:lightbulb, …) the
 * same way HACS registers hacs:hacs, so the icons work in the sidebar, in any
 * icon field and in the Atelier cards.
 *
 * Line icons: Phosphor Icons (light weight), https://phosphoricons.com
 * Copyright (c) 2023 Phosphor Icons — MIT License, full text in PHOSPHOR-LICENSE.txt.
 */
(() => {
  const ICONS = %s;
  window.customIcons = window.customIcons || {};
  window.customIcons.kirion = {
    getIcon: async (name) => ICONS[name],
    getIconList: async () => Object.keys(ICONS).map((name) => ({ name })),
  };
})();
"""
    % json.dumps(icons, separators=(",", ":")),
    encoding="utf-8",
)
LICENSE_OUT.write_text((PHOSPHOR / "LICENSE").read_text(encoding="utf-8"), encoding="utf-8")
print(f"wrote {OUT.relative_to(ROOT)}: {len(icons)} icons, {OUT.stat().st_size // 1024} KB")
