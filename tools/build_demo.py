"""Write demo/themes.generated.js from the integration's palette code.

Run from the repo root:  python3 tools/build_demo.py
"""

import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location(
    "palette", ROOT / "custom_components" / "kirion_atelier" / "palette.py"
)
palette = importlib.util.module_from_spec(spec)
spec.loader.exec_module(palette)

themes = {
    name: palette.build_theme({"accent": accent})
    for name, accent in palette.PRESETS.values()
}
out = ROOT / "demo" / "themes.generated.js"
out.write_text(
    "// GENERATED by tools/build_demo.py — one entry per Atelier preset.\n"
    f"export const THEMES = {json.dumps(themes, indent=2)};\n",
    encoding="utf-8",
)
print("wrote", out.relative_to(ROOT))
